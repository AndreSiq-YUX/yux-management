import {createHash} from 'node:crypto'
import {writeFile,rename} from 'node:fs/promises'
import {pathToFileURL} from 'node:url'

const sourceUrl='https://servicodados.ibge.gov.br/api/v1/localidades/municipios?view=nivelado'
const statePrefixes={RO:11,AC:12,AM:13,RR:14,PA:15,AP:16,TO:17,MA:21,PI:22,CE:23,RN:24,PB:25,PE:26,AL:27,SE:28,BA:29,MG:31,ES:32,RJ:33,SP:35,PR:41,SC:42,RS:43,MS:50,MT:51,GO:52,DF:53}
const normalizeName=value=>value.normalize('NFD').replace(/[\u0300-\u036f]/g,'').trim().toLocaleLowerCase('pt-BR')

/** Validate the entire official payload before touching the checked-in catalog. */
export function normalizeMunicipalities(value){
  if(!Array.isArray(value))throw Error('invalid_municipality_catalog')
  const ids=new Set(),keys=new Set(),states=new Set()
  const rows=value.map(item=>{
    const id=item?.['municipio-id'],name=item?.['municipio-nome'],state=item?.['UF-sigla']
    if(!Number.isSafeInteger(id)||!/^\d{7}$/.test(String(id))||!statePrefixes[state]||!String(id).startsWith(String(statePrefixes[state]))||typeof name!=='string'||!name.trim()||name.length>120)throw Error('invalid_municipality_record')
    const key=`${state}:${normalizeName(name)}`
    if(ids.has(id)||keys.has(key))throw Error('duplicate_municipality_record')
    ids.add(id);keys.add(key);states.add(state)
    return[state,name.trim(),id]
  })
  if(rows.length<5000||rows.length>10000||states.size!==27)throw Error('incomplete_municipality_catalog')
  return rows.sort((a,b)=>a[2]-b[2])
}

async function update(){
  const response=await fetch(sourceUrl,{signal:AbortSignal.timeout(30000),headers:{Accept:'application/json'}})
  if(!response.ok)throw Error(`municipality_catalog_http_${response.status}`)
  const rows=normalizeMunicipalities(await response.json())
  const metadata={sourceUrl,retrievedAt:new Date().toISOString(),records:rows.length,states:27,sha256:createHash('sha256').update(JSON.stringify(rows)).digest('hex')}
  const body=`// Generated by scripts/update-radar-municipalities.mjs; do not edit manually.\n// Public official IBGE locality identifiers; no provider credentials or client data.\nexport const radarMunicipalitiesMetadata=${JSON.stringify(metadata)}\nexport const radarMunicipalitiesData:ReadonlyArray<readonly [string,string,number]>=[\n${rows.map(row=>JSON.stringify(row)).join(',\n')}\n]\n`
  const output=new URL('../src/modules/radar/data/municipalities.generated.ts',import.meta.url)
  const temporary=new URL(`${output.href}.tmp`)
  await writeFile(temporary,body,'utf8')
  await rename(temporary,output)
  console.log(JSON.stringify(metadata))
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href)await update()
