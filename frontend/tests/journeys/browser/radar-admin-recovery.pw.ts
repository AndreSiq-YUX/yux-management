import path from 'node:path'
import {test,expect} from '@playwright/test'
const campaign=process.env.YUX_RADAR_RECOVERY_QA_CAMPAIGN,org=process.env.YUX_RADAR_RECOVERY_QA_ORG
test.use({baseURL:'http://127.0.0.1:4174',channel:process.env.YUX_RADAR_QA_BROWSER_CHANNEL})
test.skip(!campaign||!org,'Requires an isolated local recovery fixture, never production.')
for(const width of [1280,430])test(`scoped recovery shows durable registration and an individual blocker (${width}px)`,async({page})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 await page.setViewportSize({width,height:940})
 await page.goto('/auth/login');await expect(page).toHaveTitle(/YUX/)
 await page.getByRole('textbox',{name:'E-mail',exact:true}).fill('yux-admin@integration.test')
 await page.getByLabel('Senha',{exact:true}).fill('integration-password')
 await page.getByRole('button',{name:'Entrar',exact:true}).click();await expect(page).not.toHaveURL(/\/auth\/login/)
 await page.goto(`/admin/integrations?radarOrganization=${org}&radarCampaign=${campaign}#radar-operations`)
 const panel=page.getByRole('region',{name:'Conciliação e retomada de pesquisas'})
 await expect(panel).toContainText('Empresa Alfa');await expect(panel).toContainText('Empresa Beta')
 await panel.getByRole('checkbox',{name:'Selecionar análises desta página'}).check()
 const resume=panel.getByRole('button',{name:'Autorizar nova tentativa e retomar',exact:true})
 await expect(resume).toBeDisabled()
 await panel.locator('input[name="acknowledgePreviousCharge"]').check()
 await resume.click()
 await expect(panel).toContainText('1 retomadas registradas')
 await expect(panel.getByRole('list',{name:'Resultado da retomada'})).toContainText('Empresa Alfa: retomada registrada')
 await expect(panel.getByRole('list',{name:'Resultado da retomada'})).toContainText('Empresa Beta: falta uma rota ativa para esta etapa no painel de modelos')
 await expect(panel).toContainText('1 na fila');await expect(panel).not.toContainText('Não foi possível confirmar toda a retomada')
 await expect(page.locator('vite-error-overlay')).toHaveCount(0)
 const bounds=await panel.boundingBox();expect(bounds!.x).toBeGreaterThanOrEqual(0);expect(bounds!.x+bounds!.width).toBeLessThanOrEqual(width+1)
 if(process.env.YUX_RADAR_QA_ARTIFACTS)await panel.screenshot({path:path.join(process.env.YUX_RADAR_QA_ARTIFACTS,`admin-recovery-${width}.png`)})
 expect(errors).toEqual([])
})
